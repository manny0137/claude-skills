#!/usr/bin/env python3
"""agent_office.py — serve the Agent Office: a live view of the skill agents at work.

Start it in a second terminal, then use Claude Code as usual in this repo:

  python3 scripts/agent_office.py            # http://127.0.0.1:8765
  python3 scripts/agent_office.py --port 9000 --no-browser

The page (.claude/agent-roster/office.html, generated by
scripts/build_skill_agents.py) shows the master desk and every team's room.
Agents light up when they are dispatched, show the tool they are using, and
settle with their report status (DONE / NEEDS-INPUT / OUT-OF-SCOPE).

Events come from the hook .claude/hooks/agent_activity.py, which appends to
.claude/agent-roster/activity.jsonl. This server tails that file and pushes
new lines to the browser over Server-Sent Events.

Routes:
  /              the office page, in live mode
  /events        SSE stream (the last --backlog events, then new ones)
  /activity.jsonl  the raw log

Binds to 127.0.0.1 only. Stdlib only.
"""

import argparse
import json
import sys
import time
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROSTER = ROOT / ".claude" / "agent-roster"
PAGE = ROSTER / "office.html"
LOG = ROSTER / "activity.jsonl"


def tail_lines(path: Path, n: int) -> list:
    if not path.exists() or n <= 0:
        return []
    return [l for l in path.read_text(encoding="utf-8", errors="ignore").splitlines() if l.strip()][-n:]


class Handler(BaseHTTPRequestHandler):
    backlog = 200

    def log_message(self, fmt, *args):  # quiet
        pass

    def _send(self, code, body: bytes, ctype: str):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path in ("/", "/index.html"):
            if not PAGE.exists():
                return self._send(500, b"office.html missing: run python3 scripts/build_skill_agents.py",
                                  "text/plain; charset=utf-8")
            page = PAGE.read_text(encoding="utf-8")
            live = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
                    '<script>window.AGENT_OFFICE_LIVE = true;</script>')
            return self._send(200, (live + page).encode("utf-8"), "text/html; charset=utf-8")
        if path == "/activity.jsonl":
            body = LOG.read_bytes() if LOG.exists() else b""
            return self._send(200, body, "application/x-ndjson")
        if path == "/events":
            return self._stream()
        self._send(404, b"not found", "text/plain")

    def _stream(self):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Connection", "keep-alive")
        self.end_headers()
        try:
            for line in tail_lines(LOG, self.backlog):
                self.wfile.write(f"event: backlog\ndata: {line}\n\n".encode())
            self.wfile.write(b"event: ready\ndata: {}\n\n")
            self.wfile.flush()
            pos = LOG.stat().st_size if LOG.exists() else 0
            idle = 0.0
            while True:
                time.sleep(0.4)
                idle += 0.4
                size = LOG.stat().st_size if LOG.exists() else 0
                if size < pos:  # log was rotated
                    pos = 0
                if size > pos:
                    with LOG.open("rb") as fh:
                        fh.seek(pos)
                        chunk = fh.read(size - pos)
                    pos = size
                    for raw in chunk.decode("utf-8", errors="ignore").splitlines():
                        try:
                            json.loads(raw)
                        except ValueError:
                            continue
                        self.wfile.write(f"data: {raw}\n\n".encode())
                    self.wfile.flush()
                    idle = 0.0
                elif idle >= 15:
                    self.wfile.write(b": keep-alive\n\n")
                    self.wfile.flush()
                    idle = 0.0
        except (BrokenPipeError, ConnectionResetError):
            return


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--backlog", type=int, default=200, help="past events sent when the page opens")
    ap.add_argument("--no-browser", action="store_true", help="don't open a browser tab")
    args = ap.parse_args()

    Handler.backlog = args.backlog
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    server.daemon_threads = True
    url = f"http://127.0.0.1:{args.port}/"
    print(f"Agent Office live at {url}  (Ctrl+C to stop)")
    print(f"  watching {LOG.relative_to(ROOT)}")
    if not args.no_browser:
        try:
            webbrowser.open(url)
        except Exception:
            pass
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
