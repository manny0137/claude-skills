def parse_frontmatter(text: str) -> dict:
    """Minimal YAML frontmatter reader: plain, quoted, and folded/literal scalars."""
    m = re.match(r"---\r?\n(.*?)\r?\n---", text, re.S)
    if not m:
        return {}
    out, lines, i = {}, m.group(1).splitlines(), 0
    while i < len(lines):
        km = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", lines[i])
        i += 1
        if not km:
            continue
        key, val = km.group(1), km.group(2).strip()
        if val in (">", "|", ">-", "|-", ">+", "|+", ""):
            block = []
            while i < len(lines) and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                block.append(lines[i].strip())
                i += 1
            val = " ".join(b for b in block if b) if val.startswith(">") or val == "" else "\n".join(block)
        out[key] = val.strip().strip('"').strip("'")
    return out


def short_description(desc: str) -> str:
    desc = re.sub(r"\s+", " ", desc).strip()
    if len(desc) <= DESC_LIMIT:
        return desc
    cut = desc[:DESC_LIMIT]
    for stop in (". ", "; "):
        idx = cut.rfind(stop)
        if idx > 80:
            return cut[: idx + 1]
    return cut.rsplit(" ", 1)[0].rstrip(",;:") + "…"


def list_files(folder: Path, sub: str, suffix: str, limit: int = 10) -> list:
    d = folder / sub
    if not d.is_dir():
        return []
    files = sorted(p for p in d.rglob(f"*{suffix}") if p.is_file() and "__pycache__" not in p.parts)
    return [str(p.relative_to(REPO_ROOT)) for p in files[:limit]]


def collect(domains=None) -> list:
    """Return deduplicated skill records, one per agent."""
    raw = []
    for p in canonical_walk(REPO_ROOT):
        if p.name != "SKILL.md":
            continue
        rel = p.relative_to(REPO_ROOT)
        domain = rel.parts[0]
        if domains and domain not in domains:
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        fm = parse_frontmatter(text)
        name = re.sub(r"[^a-z0-9-]+", "-", (fm.get("name") or p.parent.name).lower()).strip("-")
        raw.append({
            "skill": name,
            "domain": domain,
            "path": str(rel),
            "dir": str(rel.parent),
            "description": fm.get("description", ""),
            "digest": hashlib.sha256(text.encode()).hexdigest(),
        })

    # Dual-published copies: keep the shortest path (the domain bundle copy).
    by_digest = {}
    for r in sorted(raw, key=lambda r: (len(r["path"]), r["path"])):
        by_digest.setdefault(r["digest"], r)
    skills = list(by_digest.values())

    # Distinct skills that share a name: prefix with the nearest distinguishing folder.
    by_name = {}
    for r in skills:
        by_name.setdefault(r["skill"], []).append(r)
    for name, group in by_name.items():
        for r in group:
            if len(group) == 1:
                r["agent"] = f"sk-{name}"
            else:
                parts = [x for x in Path(r["dir"]).parts if x not in ("skills", name)]
                r["agent"] = f"sk-{parts[-1]}-{name}" if parts else f"sk-{r['domain']}-{name}"

    for r in skills:
        folder = REPO_ROOT / r["dir"]
        r["color"] = DOMAIN_COLORS.get(r["domain"], "blue")
        r["domain_label"] = DOMAIN_LABELS.get(r["domain"], r["domain"])
        r["summary"] = short_description(r["description"]) or f"{r['skill']} skill agent."
        r["scripts"] = list_files(folder, "scripts", ".py")
        r["references"] = list_files(folder, "references", ".md")
        r["title"] = r["skill"].replace("-", " ").title()
        del r["digest"]
    return sorted(skills, key=lambda r: (r["domain"], r["agent"]))


