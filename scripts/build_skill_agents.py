def planned_files(skills: list) -> dict:
    files = {AGENTS_DIR / f"{r['agent']}.md": render_agent(r, len(skills)) for r in skills}
    files[MASTER_FILE] = render_master(skills)
    files[ROSTER_DIR / "registry.json"] = render_registry(skills)
    files[ROSTER_DIR / "roster.html"] = render_roster(skills)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files are stale; no writes")
    ap.add_argument("--domains", help="comma-separated top-level domains to include (default: all)")
    ap.add_argument("--list", action="store_true", help="print the roster and exit")
    args = ap.parse_args()

    domains = set(args.domains.split(",")) if args.domains else None
    skills = collect(domains)
    if not skills:
        print("no skills found", file=sys.stderr)
        return 1

    if args.list:
        for r in skills:
            print(f"{r['agent']:<48} {r['color']:<7} {r['domain_label']}")
        print(f"\n{len(skills)} agents + {MASTER_NAME}")
        return 0

    files = planned_files(skills)
    existing = set(AGENTS_DIR.glob("sk-*.md")) if AGENTS_DIR.is_dir() else set()
    stale = [p for p in existing if p not in files]
    changed = [p for p, body in files.items() if not p.exists() or p.read_text(encoding="utf-8") != body]

    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        for p in stale:
            print(f"stale: {p.relative_to(REPO_ROOT)}")
        if changed or stale:
            print("run: python3 scripts/build_skill_agents.py")
            return 1
        print(f"OK — {len(skills)} skill agents + {MASTER_NAME} are up to date")
        return 0

    for p in stale:
        p.unlink()
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print(f"{len(skills)} skill agents + {MASTER_NAME}: {len(changed)} written, {len(stale)} removed")
    print(f"  agents:   {AGENTS_DIR.relative_to(REPO_ROOT)}/")
    print(f"  master:   {MASTER_FILE.relative_to(REPO_ROOT)}")
    print(f"  roster:   {(ROSTER_DIR / 'roster.html').relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
